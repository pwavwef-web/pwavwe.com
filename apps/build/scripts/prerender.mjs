// Writes the public Pwavwe Studio pages as static HTML into the pwavwe.com
// hosting root (the repository root), so crawlers and no-JS visitors read the
// full page, then the client bundle hydrates it. Run via `npm run build:site`.
//
//   /studio        -> studio.html          /work/comitia -> work/comitia.html
//   /studio/about  -> studio/about.html    /services     -> services.html
//
// Assets land in /studio/ (the site build's base path). sitemap.xml is
// regenerated from the same route list so it can never drift from the pages.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const siteRoot = resolve(appDir, '../..');
const clientDir = join(appDir, 'dist-site');
const MARKER = '.generated-by-prerender';
const SITE_ORIGIN = 'https://pwavwe.com';

// Pages of the personal site itself, listed alongside the Studio pages.
const ROOT_PAGES = [
  { path: '/', priority: '1.0' },
  { path: '/academy/foundations', priority: '0.5' },
];

const escapeHtml = (value) => String(value)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function decodeFirestore(value) {
  if ('stringValue' in value) return value.stringValue;
  if ('integerValue' in value) return Number(value.integerValue);
  if ('doubleValue' in value) return value.doubleValue;
  if ('booleanValue' in value) return value.booleanValue;
  if ('timestampValue' in value) return value.timestampValue;
  if ('mapValue' in value) return Object.fromEntries(Object.entries(value.mapValue.fields ?? {}).map(([key, item]) => [key, decodeFirestore(item)]));
  if ('arrayValue' in value) return (value.arrayValue.values ?? []).map(decodeFirestore);
  return null;
}

// publicTestimonials is world-readable (see firestore.rules), so the REST API
// needs no credentials. A failed fetch only means the page loads them live.
async function fetchTestimonials() {
  const fields = ['name', 'role', 'organisation', 'quote', 'rating', 'projectName', 'featured', 'order', 'sourceId'];
  const url = 'https://firestore.googleapis.com/v1/projects/francis-pwavwe/databases/(default)/documents/publicTestimonials?pageSize=60&orderBy=approvedAt%20desc';
  try {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const { documents = [] } = await response.json();
    const items = documents.map((document) => {
      const data = decodeFirestore({ mapValue: { fields: document.fields ?? {} } });
      return Object.fromEntries(fields.filter((key) => data[key] !== undefined && data[key] !== null).map((key) => [key, data[key]]));
    });
    return items.sort((a, b) => Number(Boolean(b.featured)) - Number(Boolean(a.featured)) || (a.order ?? 0) - (b.order ?? 0));
  } catch (error) {
    console.warn(`prerender: testimonials not embedded (${error.message})`);
    return null;
  }
}

function headTags(head) {
  const tags = [
    `<title>${escapeHtml(head.title)}</title>`,
    `<meta name="description" content="${escapeHtml(head.description)}" />`,
    `<link rel="canonical" href="${escapeHtml(head.url)}" />`,
    `<meta name="robots" content="${head.noIndex ? 'noindex,nofollow' : 'index,follow'}" />`,
    `<meta property="og:title" content="${escapeHtml(head.title)}" />`,
    `<meta property="og:description" content="${escapeHtml(head.description)}" />`,
    `<meta property="og:url" content="${escapeHtml(head.url)}" />`,
    `<meta property="og:image" content="${escapeHtml(head.image)}" />`,
    `<meta name="twitter:title" content="${escapeHtml(head.title)}" />`,
    `<meta name="twitter:description" content="${escapeHtml(head.description)}" />`,
    `<meta name="twitter:image" content="${escapeHtml(head.image)}" />`,
  ];
  return tags.join('\n    ');
}

// Only ever delete output this script created.
function clearGenerated(path) {
  if (!existsSync(path)) return;
  if (!existsSync(join(path, MARKER))) throw new Error(`prerender: refusing to replace ${path}; it was not generated by this script`);
  rmSync(path, { recursive: true, force: true });
}

const template = readFileSync(join(clientDir, 'site.html'), 'utf8');
const { render, sitePaths } = await import(pathToFileURL(join(appDir, 'dist-ssr', 'entry-server.js')).href);

const testimonials = await fetchTestimonials();
globalThis.__STUDIO_PREFETCH__ = { testimonials };
const dataScript = `<script>window.__STUDIO_PREFETCH__=${JSON.stringify({ testimonials }).replace(/</g, '\\u003c')}</script>`;

// Reset previous output.
for (const dir of ['studio', 'work']) clearGenerated(join(siteRoot, dir));
for (const path of sitePaths) {
  const file = join(siteRoot, `${path}.html`);
  if (existsSync(file) && !path.includes('/', 1)) rmSync(file);
}

// Static assets (JS, CSS, covers, fonts) under /studio/.
const studioDir = join(siteRoot, 'studio');
mkdirSync(studioDir, { recursive: true });
writeFileSync(join(studioDir, MARKER), 'Generated by apps/build/scripts/prerender.mjs\n');
const skip = new Set(['site.html', 'robots.txt', 'sitemap.xml', 'site.webmanifest']);
for (const entry of readdirSync(clientDir)) {
  if (!skip.has(entry)) cpSync(join(clientDir, entry), join(studioDir, entry), { recursive: true });
}
mkdirSync(join(siteRoot, 'work'), { recursive: true });
writeFileSync(join(siteRoot, 'work', MARKER), 'Generated by apps/build/scripts/prerender.mjs\n');

for (const path of sitePaths) {
  const { html, head } = render(path);
  if (!head) throw new Error(`prerender: ${path} rendered without a <Seo> head`);
  const page = template
    .replace('<!--studio-head-->', headTags(head))
    .replace('<!--studio-app-->', html)
    .replace('<!--studio-data-->', dataScript);
  const file = join(siteRoot, `${path}.html`);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, page);
  console.log(`prerender: ${path} -> ${file.slice(siteRoot.length + 1)}`);
}

const today = new Date().toISOString().slice(0, 10);
const urls = [
  ...ROOT_PAGES,
  ...sitePaths.map((path) => ({ path, priority: path === '/studio' || path === '/work' ? '0.9' : path.startsWith('/work/') ? '0.8' : '0.6' })),
];
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by apps/build/scripts/prerender.mjs. Edit ROOT_PAGES there, not here. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(({ path, priority }) => `  <url><loc>${SITE_ORIGIN}${path}</loc><lastmod>${today}</lastmod><priority>${priority}</priority></url>`).join('\n')}
</urlset>
`;
writeFileSync(join(siteRoot, 'sitemap.xml'), sitemap);
console.log(`prerender: sitemap.xml with ${urls.length} URLs`);
